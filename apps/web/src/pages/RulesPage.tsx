import { useMemo, useState } from 'react';
import {
  REBUILT_2026,
  REBUILT_FIELD,
  RULE_CATALOG,
  type RuleCategory,
  type RuleDefinition,
} from '@rebuilt/shared';
import { Icon } from '../components/Icon';

const FILTERS: Array<{ id: 'all' | RuleCategory; label: string }> = [
  { id: 'all', label: 'All rules' },
  { id: 'conduct', label: 'Conduct & contact' },
  { id: 'robot', label: 'Robot construction' },
  { id: 'human', label: 'Human players' },
  { id: 'scoring', label: 'Scoring elements' },
  { id: 'cards', label: 'Cards & discipline' },
  { id: 'field', label: 'Field protection' },
];

const DETECTION_LABEL = {
  automatic: 'Auto-called',
  review: 'Queued for review',
  'referee-only': 'Referee call',
} as const;

function RuleCard({ rule }: { rule: RuleDefinition }) {
  return (
    <article className={`rule-card severity-${rule.severity}`} id={rule.id}>
      <div className="rule-card-head">
        <span className="rule-id">{rule.id}</span>
        <span className={`detection-chip ${rule.detection}`}>
          <span className="status-dot" /> {DETECTION_LABEL[rule.detection]}
        </span>
        {rule.card && (
          <span className={`card-chip ${rule.card}`}>
            <Icon name="flag" size={11} /> {rule.card === 'conditional' ? 'CARD AT REF DISCRETION' : `${rule.card.toUpperCase()} CARD`}
          </span>
        )}
      </div>
      <h3>{rule.title}</h3>
      <p>{rule.summary}</p>
      <div className="rule-penalty">
        <span>PENALTY</span>
        <strong>{rule.penalty}</strong>
      </div>
      <div className="rule-sim">
        <span>IN THIS SIM</span>
        <p>{rule.simulator}</p>
      </div>
    </article>
  );
}

export function RulesPage() {
  const [filter, setFilter] = useState<'all' | RuleCategory>('all');
  const [query, setQuery] = useState('');
  const [showFlow, setShowFlow] = useState(true);

  const rules = useMemo(() => {
    const search = query.trim().toLowerCase();
    return RULE_CATALOG.filter((rule) => {
      if (filter !== 'all' && rule.category !== filter) return false;
      if (!search) return true;
      return `${rule.id} ${rule.title} ${rule.summary} ${rule.penalty} ${rule.simulator}`
        .toLowerCase()
        .includes(search);
    });
  }, [filter, query]);

  const cardRules = RULE_CATALOG.filter((rule) => rule.card);

  return (
    <div className="rules-page">
      <section className="container rules-hero">
        <div className="rules-hero-copy">
          <span className="eyebrow">REBUILT presented by Haas · {REBUILT_2026.rulesVersion}</span>
          <h1>The rulebook, made playable.</h1>
          <p>
            Every foul in this simulator is generated by a physics event and judged by the rule
            engine below. When the manual and this page disagree, the official manual wins — and we
            ship a fix.
          </p>
          <div className="rules-hero-actions">
            <a
              className="btn btn-secondary btn-sm"
              href={REBUILT_2026.sourceUrl}
              target="_blank"
              rel="noreferrer"
            >
              <Icon name="book" size={14} /> Official game manual
            </a>
            <button type="button" className="btn btn-ghost btn-sm" onClick={() => setShowFlow((value) => !value)}>
              <Icon name="history" size={14} /> {showFlow ? 'Hide' : 'Show'} match flow
            </button>
          </div>
          <p className="rules-version">
            Rules snapshot {REBUILT_2026.rulesVersion} · updated {REBUILT_2026.rulesUpdated} · Section 6
            scoring, Section 7 conduct, Section 8 construction.
          </p>
        </div>
        <div className="rules-quick-card panel">
          <span className="eyebrow">At a glance</span>
          <div className="quick-rule-grid">
            <div>
              <span>FUEL · active HUB</span>
              <b>{REBUILT_2026.scoring.fuel} pt</b>
            </div>
            <div>
              <span>AUTO TOWER L1</span>
              <b>{REBUILT_2026.scoring.autoTower[1]} pts</b>
            </div>
            <div>
              <span>END GAME L1 / L2 / L3</span>
              <b>{REBUILT_2026.scoring.teleopTower[1]} / {REBUILT_2026.scoring.teleopTower[2]} / {REBUILT_2026.scoring.teleopTower[3]}</b>
            </div>
            <div>
              <span>MINOR / MAJOR FOUL</span>
              <b>{REBUILT_2026.fouls.minor} / {REBUILT_2026.fouls.major} pts</b>
            </div>
            <div>
              <span>WIN / TIE</span>
              <b>{REBUILT_2026.ranking.win} / {REBUILT_2026.ranking.tie} RP</b>
            </div>
            <div>
              <span>PIN LIMIT</span>
              <b>{REBUILT_2026.pinning.limitSeconds}s</b>
            </div>
          </div>
          <div className="quick-callout">
            <Icon name="zap" size={15} />
            <span>
              FUEL only scores when that alliance&apos;s HUB is active. Timing is everything in the
              shift game.
            </span>
          </div>
        </div>
      </section>

      {showFlow && (
        <section className="container rules-section">
          <div className="section-heading">
            <div>
              <span className="eyebrow">Match flow</span>
              <h2>2:40, four shifts, one climb.</h2>
            </div>
            <span className="section-note">HUBs alternate every shift</span>
          </div>
          <div className="timeline-strip">
            <div className="timeline-block auto">
              <div className="timeline-bar" style={{ width: `${(REBUILT_2026.timing.auto / REBUILT_2026.timing.total) * 100}%` }} />
              <span className="timeline-time">0:00 – 0:20</span>
              <strong>AUTO</strong>
              <p>20 seconds. Both HUBs active. Robots score FUEL and may climb to Level 1 for 15 points.</p>
            </div>
            <div className="timeline-block transition">
              <div className="timeline-bar" style={{ width: `${(REBUILT_2026.timing.transition / REBUILT_2026.timing.total) * 100}%` }} />
              <span className="timeline-time">0:20 – 0:30</span>
              <strong>TRANSITION</strong>
              <p>10 seconds, both HUBs still active and scoring counts. The first inactive HUB is sent to the teams as TELEOP begins.</p>
            </div>
            <div className="timeline-block shift">
              <div className="timeline-bar" style={{ width: `${((REBUILT_2026.timing.shift * REBUILT_2026.timing.shifts) / REBUILT_2026.timing.total) * 100}%` }} />
              <span className="timeline-time">0:30 – 2:10</span>
              <strong>4 × 25s SHIFTS</strong>
              <p>One HUB at a time is inactive. The alliance that scored fewer AUTO FUEL sees its HUB inactive first; ties use the FMS coin flip.</p>
            </div>
            <div className="timeline-block endgame">
              <div className="timeline-bar" style={{ width: `${(REBUILT_2026.timing.endgame / REBUILT_2026.timing.total) * 100}%` }} />
              <span className="timeline-time">2:10 – 2:40</span>
              <strong>END GAME</strong>
              <p>Both HUBs active. Climb the TOWER for 10 / 20 / 30 points. TOWER protection is live for the final 30 seconds.</p>
            </div>
          </div>
          <div className="rp-strip">
            <div className="rp-strip-head">
              <span className="eyebrow">Ranking points</span>
              <h3>Earn them on the field, not in the lobby.</h3>
            </div>
            <div className="rp-cards">
              <div>
                <span>ENERGIZED</span>
                <b>100 FUEL</b>
                <p>+1 RP · count FUEL scored by your alliance</p>
              </div>
              <div>
                <span>SUPERCHARGED</span>
                <b>360 FUEL</b>
                <p>+1 RP · the full-field scoring benchmark</p>
              </div>
              <div>
                <span>TRAVERSAL</span>
                <b>50 TOWER pts</b>
                <p>+1 RP · combined AUTO + END GAME climb points</p>
              </div>
              <div>
                <span>WIN / TIE</span>
                <b>3 / 1 RP</b>
                <p>Win the match, or tie it. Fouls do not earn RP by themselves.</p>
              </div>
            </div>
            <p className="rp-note">
              <Icon name="warning" size={13} /> A RED CARD, disqualification or alliance-level
              ineligibility removes that alliance&apos;s remaining RP eligibility for the match.
            </p>
          </div>
        </section>
      )}

      <section className="container rules-section">
        <div className="section-heading">
          <div>
            <span className="eyebrow">Penalty ladder</span>
            <h2>Warnings, fouls, cards, DQ.</h2>
          </div>
          <span className="section-note">Called by the head referee or auto-generated</span>
        </div>
        <div className="penalty-ladder">
          <div className="penalty-step">
            <span className="penalty-glyph warning"><Icon name="warning" size={17} /></span>
            <div>
              <span>STEP 1 · VERBAL</span>
              <h3>Warning</h3>
              <p>Logged, no points. G101 and other correctable issues start here when the field is safe.</p>
            </div>
            <b>0 pts</b>
          </div>
          <div className="penalty-step">
            <span className="penalty-glyph minor"><Icon name="flag" size={17} /></span>
            <div>
              <span>STEP 2 · FOUL</span>
              <h3>Minor foul</h3>
              <p>Awarded to the opponent. Examples: pinning at 3 s, illegal expansion, human reach.</p>
            </div>
            <b>{REBUILT_2026.fouls.minor} pts</b>
          </div>
          <div className="penalty-step">
            <span className="penalty-glyph major"><Icon name="shield" size={17} /></span>
            <div>
              <span>STEP 3 · FOUL</span>
              <h3>Major foul</h3>
              <p>Awarded to the opponent. Examples: AUTO cross-line contact, damage, TOWER contact in the final 30 s.</p>
            </div>
            <b>{REBUILT_2026.fouls.major} pts</b>
          </div>
          <div className="penalty-step">
            <span className="penalty-glyph yellow"><Icon name="flag" size={17} /></span>
            <div>
              <span>STEP 4 · CARD</span>
              <h3>Yellow card</h3>
              <p>Disciplinary marker for the team. A second yellow in the same tournament phase becomes a RED CARD.</p>
            </div>
            <b>+ foul</b>
          </div>
          <div className="penalty-step">
            <span className="penalty-glyph red"><Icon name="close" size={17} /></span>
            <div>
              <span>STEP 5 · DISQUALIFIED</span>
              <h3>Red card · DQ</h3>
              <p>The team is disqualified. Its robot is disabled, and the alliance loses RP eligibility for the match.</p>
            </div>
            <b>RP gone</b>
          </div>
        </div>
        <div className="card-rules-grid">
          {cardRules.map((rule) => (
            <div className={`mini-rule ${rule.card ?? ''}`} key={rule.id}>
              <span className="rule-id">{rule.id}</span>
              <strong>{rule.title}</strong>
              <p>{rule.penalty}</p>
            </div>
          ))}
        </div>
        <div className="rule-note-strip">
          <div>
            <Icon name="bot" size={16} />
            <span>
              <b>Disabled is not disqualified.</b> A disabled robot stops moving but keeps its score
              and card status. The referee can re-enable it after a field fault or safety stop.
            </span>
          </div>
          <div>
            <Icon name="shield" size={16} />
            <span>
              <b>Referee override is deliberate.</b> Events created by the engine can be confirmed or
              overturned. Manual calls need a rule ID and a note so the log is auditable.
            </span>
          </div>
        </div>
      </section>

      <section className="container rules-section rules-catalog-section">
        <div className="section-heading">
          <div>
            <span className="eyebrow">Implemented rule catalog</span>
            <h2>Every call the simulator understands.</h2>
          </div>
          <span className="section-note">{rules.length} of {RULE_CATALOG.length} rules</span>
        </div>
        <div className="rules-toolbar">
          <div className="rules-filters">
            {FILTERS.map((entry) => (
              <button
                key={entry.id}
                type="button"
                className={filter === entry.id ? 'is-active' : ''}
                onClick={() => setFilter(entry.id)}
              >
                {entry.label}
                <span>
                  {entry.id === 'all'
                    ? RULE_CATALOG.length
                    : RULE_CATALOG.filter((rule) => rule.category === entry.id).length}
                </span>
              </button>
            ))}
          </div>
          <label className="rules-search">
            <Icon name="book" size={15} />
            <input
              className="input"
              placeholder="Search G418, pinning, expansion…"
              value={query}
              onChange={(event) => setQuery(event.target.value)}
            />
          </label>
        </div>
        <div className="rule-grid">
          {rules.map((rule) => (
            <RuleCard key={rule.id} rule={rule} />
          ))}
        </div>
        {rules.length === 0 && (
          <div className="rules-empty panel">
            <Icon name="book" size={25} />
            <h3>No rule matches that search.</h3>
            <p>Try a rule number such as G418, or clear the filter.</p>
            <button
              type="button"
              className="btn btn-secondary btn-sm"
              onClick={() => {
                setQuery('');
                setFilter('all');
              }}
            >
              Clear filters
            </button>
          </div>
        )}
      </section>

      <section className="container rules-footnote">
        <div className="rules-source-card panel">
          <span className="eyebrow">Source of truth</span>
          <h2>Official manual, not a wiki.</h2>
          <p>
            Scoring values, shift timing, fouls, card policy and robot limits are defined in the
            official REBUILT game manual and Team Updates. This simulator versions its rule data so a
            future update can change numbers without rewriting the physics.
          </p>
          <div className="rules-source-actions">
            <a className="btn btn-primary btn-sm" href={REBUILT_2026.sourceUrl} target="_blank" rel="noreferrer">
              <Icon name="arrow" size={14} /> Read the 2026 manual
            </a>
            <a className="btn btn-ghost btn-sm" href="https://www.firstinspires.org/robotics/frc/game-and-season" target="_blank" rel="noreferrer">
              FIRST game &amp; season
            </a>
          </div>
          <small>
            Rules version {REBUILT_2026.rulesVersion} · game ID {REBUILT_2026.id} · playfield{' '}
            {(REBUILT_FIELD.size.length / 0.3048).toFixed(0)} ft × {(REBUILT_FIELD.size.width / 0.3048).toFixed(0)} ft
            (scaled up from the {((REBUILT_2026.field.length / 0.3048)).toFixed(0)} ft ×{' '}
            {(REBUILT_2026.field.width / 0.3048).toFixed(0)} ft carpet).
            Unofficial fan simulator; not affiliated with FIRST.
          </small>
        </div>
      </section>
    </div>
  );
}
